export function getRandomWords(
  count,
  exclude = [],
  categories = ['base'],
  customWords = []
) {
  let availableObjects = customWords.map(w => ({
    ru: w.trim().toUpperCase(),
    en: w.trim().toUpperCase()
  }));

  categories.forEach(cat => {
    if (cat !== 'custom') {
      const ruWords = CATEGORIES['ru']?.[cat] || [];
      const enWords = CATEGORIES['en']?.[cat] || [];

      const maxLen = Math.max(ruWords.length, enWords.length);
      for (let i = 0; i < maxLen; i++) {
        const ruWord = (ruWords[i] || enWords[i]).trim().toUpperCase();
        const enWord = (enWords[i] || ruWords[i]).trim().toUpperCase();

        availableObjects.push({
          ru: ruWord,
          en: enWord
        });
      }
    }
  });

  const uniqueMap = new Map();
  availableObjects.forEach(obj => {
    if (obj.ru.trim().length > 0 && !exclude.includes(obj.ru)) {
      uniqueMap.set(obj.ru, obj);
    }
  });

  let available = Array.from(uniqueMap.values());

  if (available.length < count) {
    const ruFallback = CATEGORIES['ru'].base;
    const enFallback = CATEGORIES['en'].base;
    ruFallback.forEach((ruWord, index) => {
      const ruUpper = ruWord.trim().toUpperCase();
      if (!exclude.includes(ruUpper) && !uniqueMap.has(ruUpper)) {
        available.push({
          ru: ruUpper,
          en: (enFallback[index] || ruWord).trim().toUpperCase()
        });
      }
    });
  }

  const shuffled = [...available].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}
